def kpi_card(s, x, y, w, h, label, value, delta, vc=NAVY):
    rrect(s, x, y, w, h, WHITE)
    text(s, x+0.2, y+0.14, w-0.4, 0.3, label, size=11.5, color=SUB)
    text(s, x+0.2, y+0.44, w-0.4, 0.55, value, size=25, bold=True, color=vc)
    text(s, x+0.2, y+1.02, w-0.4, 0.3, delta, size=10.5, color=GREEN if "▲" in delta or "省" in delta or "✓" in delta else SUB)

def bullet_card(s, x, y, w, h, title, items, tc=NAVY):
    rrect(s, x, y, w, h, WHITE)
    text(s, x+0.22, y+0.14, w-0.44, 0.35, title, size=14, bold=True, color=tc)
    lines = [("· " + it, {"size": 11.5, "space": 5}) for it in items]
    text(s, x+0.22, y+0.56, w-0.44, h-0.7, lines, size=11.5, color=INK)

def bar_row(s, x, y, w, label, pct, val, color=GOLD, lw=1.7):
    text(s, x, y, lw, 0.3, label, size=11, color=SUB)
